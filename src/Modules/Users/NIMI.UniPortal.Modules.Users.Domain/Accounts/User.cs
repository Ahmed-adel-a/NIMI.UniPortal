using NIMI.UniPortal.Modules.Users.Domain.Organization;

namespace NIMI.UniPortal.Modules.Users.Domain.Accounts;

/// <summary>
/// An account of any role. Passwords arrive already hashed (hashing is infrastructure).
/// Accounts are deactivated, never deleted; academic history elsewhere keeps pointing at the id.
/// </summary>
public sealed class User
{
    private User()
    {
    }

    public Guid Id { get; private set; }

    public string FullName { get; private set; } = null!;

    /// <summary>Normalized (trimmed, lower-case) — see <see cref="EmailAddress"/>.</summary>
    public string Email { get; private set; } = null!;

    public string PasswordHash { get; private set; } = null!;

    public UserRole Role { get; private set; }

    /// <summary>Required for students, professors and department heads; null for admins.</summary>
    public Guid? DepartmentId { get; private set; }

    /// <summary>Students only. Generated once, never changes.</summary>
    public string? StudentCode { get; private set; }

    /// <summary>Teaching staff only; display only.</summary>
    public AcademicTitle? AcademicTitle { get; private set; }

    public string? NationalId { get; private set; }

    public DateOnly? DateOfBirth { get; private set; }

    public Gender? Gender { get; private set; }

    /// <summary>Students only.</summary>
    public int? EnrollmentYear { get; private set; }

    public string? Phone { get; private set; }

    public bool IsActive { get; private set; }

    /// <summary>True for every account created with a temporary password (decision AUTH).</summary>
    public bool MustChangePassword { get; private set; }

    public int FailedLoginCount { get; private set; }

    public DateTimeOffset? LockedUntil { get; private set; }

    public DateTimeOffset? LastLoginAt { get; private set; }

    public DateTimeOffset CreatedAt { get; private set; }

    public DateTimeOffset? UpdatedAt { get; private set; }

    /// <summary>A Student Affairs account; personal details (national ID, phone…) are optional for admins.</summary>
    public static User CreateAdmin(
        string fullName, string email, string passwordHash, bool mustChangePassword, DateTimeOffset now, PersonalDetails? details = null)
    {
        var admin = New(UserRole.Admin, fullName, email, passwordHash, mustChangePassword, now);
        if (details is not null)
            admin.Apply(details);
        return admin;
    }

    /// <summary>A new student. <paramref name="studentCode"/> is generated by the caller (atomic counter) and never changes.</summary>
    public static User CreateStudent(
        string fullName,
        string email,
        string passwordHash,
        Department department,
        int enrollmentYear,
        string studentCode,
        PersonalDetails details,
        DateTimeOffset now)
    {
        RequireActive(department);
        if (enrollmentYear is < 1950 or > 2100)
            throw new ArgumentOutOfRangeException(nameof(enrollmentYear), enrollmentYear, "Must be a year between 1950 and 2100.");
        if (string.IsNullOrWhiteSpace(studentCode))
            throw new ArgumentException("Required.", nameof(studentCode));

        var student = New(UserRole.Student, fullName, email, passwordHash, mustChangePassword: true, now);
        student.DepartmentId = department.Id;
        student.EnrollmentYear = enrollmentYear;
        student.StudentCode = studentCode;
        student.Apply(details);
        return student;
    }

    /// <summary>A new member of the teaching team (role professor; the rank is display-only).</summary>
    public static User CreateProfessor(
        string fullName,
        string email,
        string passwordHash,
        Department department,
        AcademicTitle academicTitle,
        PersonalDetails details,
        DateTimeOffset now)
    {
        RequireActive(department);
        if (!Enum.IsDefined(academicTitle))
            throw new ArgumentOutOfRangeException(nameof(academicTitle), academicTitle, "Unknown academic title.");

        var professor = New(UserRole.Professor, fullName, email, passwordHash, mustChangePassword: true, now);
        professor.DepartmentId = department.Id;
        professor.AcademicTitle = academicTitle;
        professor.Apply(details);
        return professor;
    }

    /// <summary>
    /// A new department head (decision ROLES2): the supervisor of one department, who may also be assigned to teach.
    /// The academic title is optional and display-only. One active head per department is checked by the caller.
    /// </summary>
    public static User CreateDepartmentHead(
        string fullName,
        string email,
        string passwordHash,
        Department department,
        AcademicTitle? academicTitle,
        PersonalDetails details,
        DateTimeOffset now)
    {
        RequireActive(department);
        if (academicTitle is { } title && !Enum.IsDefined(title))
            throw new ArgumentOutOfRangeException(nameof(academicTitle), academicTitle, "Unknown academic title.");

        var head = New(UserRole.DepartmentHead, fullName, email, passwordHash, mustChangePassword: true, now);
        head.DepartmentId = department.Id;
        head.AcademicTitle = academicTitle;
        head.Apply(details);
        return head;
    }

    public bool IsLockedOut(DateTimeOffset now) => LockedUntil > now;

    /// <summary>A wrong password. The 5th in a row locks the account and starts counting again.</summary>
    public void RecordFailedLogin(DateTimeOffset now)
    {
        FailedLoginCount++;
        if (FailedLoginCount >= LoginLockout.MaxFailedAttempts)
        {
            LockedUntil = now + LoginLockout.Duration;
            FailedLoginCount = 0;
        }
    }

    public void RecordSuccessfulLogin(DateTimeOffset now)
    {
        FailedLoginCount = 0;
        LockedUntil = null;
        LastLoginAt = now;
    }

    /// <summary>The user chose their own password: the forced change is satisfied.</summary>
    public void ChangePassword(string newPasswordHash, DateTimeOffset now)
    {
        PasswordHash = RequiredHash(newPasswordHash);
        MustChangePassword = false;
        UpdatedAt = now;
    }

    /// <summary>
    /// The user proved control of their email ("forgot password"): their own new password, no forced change, and the
    /// lockout cleared.
    /// </summary>
    public void ResetPasswordByEmail(string newPasswordHash, DateTimeOffset now)
    {
        PasswordHash = RequiredHash(newPasswordHash);
        MustChangePassword = false;
        FailedLoginCount = 0;
        LockedUntil = null;
        UpdatedAt = now;
    }

    /// <summary>Admin reset: a new temporary password, forced change, lockout cleared.</summary>
    public void ResetPassword(string temporaryPasswordHash, DateTimeOffset now)
    {
        PasswordHash = RequiredHash(temporaryPasswordHash);
        MustChangePassword = true;
        FailedLoginCount = 0;
        LockedUntil = null;
        UpdatedAt = now;
    }

    public void SetActive(bool isActive, DateTimeOffset now)
    {
        IsActive = isActive;
        UpdatedAt = now;
    }

    private static User New(UserRole role, string fullName, string email, string passwordHash, bool mustChangePassword, DateTimeOffset now) =>
        new()
        {
            Id = Guid.CreateVersion7(),
            Role = role,
            FullName = Name(fullName),
            Email = EmailAddress.Normalize(email, nameof(email)),
            PasswordHash = RequiredHash(passwordHash),
            IsActive = true,
            MustChangePassword = mustChangePassword,
            CreatedAt = now,
        };

    private void Apply(PersonalDetails details)
    {
        NationalId = Optional(details.NationalId, 50, "nationalId");
        Phone = Optional(details.Phone, 20, "phone");
        DateOfBirth = details.DateOfBirth;
        Gender = details.Gender;
    }

    private static void RequireActive(Department department)
    {
        if (!department.IsActive)
            throw new ArgumentException("The department is deactivated.", "departmentId");
    }

    private static string? Optional(string? value, int maxLength, string paramName)
    {
        if (string.IsNullOrWhiteSpace(value))
            return null;
        var trimmed = value.Trim();
        return trimmed.Length <= maxLength ? trimmed : throw new ArgumentException($"At most {maxLength} characters.", paramName);
    }

    private static string Name(string fullName)
    {
        if (string.IsNullOrWhiteSpace(fullName))
            throw new ArgumentException("Required.", nameof(fullName));
        var trimmed = fullName.Trim();
        return trimmed.Length <= 255 ? trimmed : throw new ArgumentException("At most 255 characters.", nameof(fullName));
    }

    private static string RequiredHash(string hash) =>
        string.IsNullOrEmpty(hash) ? throw new ArgumentException("A password hash is required.", "password") : hash;
}
